"""Build a BibTeX seed file for `dream-dynamics.md` from a curated identifier table.

The manuscript's reference list was maintained by hand as 49 numbered entries. Six of those
(5, 17, 18, 22, 25, 38) bundle two distinct works into one number ("...(See also ...)"), one
— number 36 — is a prose note about data providers rather than a citable work, and seven are
books or monographs with no registered DOI. This script resolves the curated table below into
BibTeX entries: most fetched from Crossref and checked against what the printed list actually
claims, seven written out by hand.

The list the records are checked *against* is no longer inside the manuscript. On 2026-08-24
`dream-dynamics.md` moved to `[@citekey]` markers with the bibliography generated by pandoc, so
the hand-curated numbered list moved to `references-numbered-archive.md` and this script reads
it from there. Retiring the archive would leave the bibliography unverifiable against anything;
see the header of that file. Entries 50 onward were added after the move and never carried a
printed number in the manuscript.

Output is a *seed*: it exists to be imported into Zotero once (File -> Import). After that,
Zotero plus Better BibTeX owns the bibliography and auto-exports to `references.bib`, so this
script deliberately writes to a different filename and never touches that path. Citation keys
here are the ones the manuscript cites, so an import that lets BBT reassign keys from its own
formula will break every marker: pin the imported keys instead.

Verification is not optional. Every fetched record must agree with the printed entry on first
author, year, and a majority of title words; disagreement is reported and, with --strict, is
fatal. That is the check that catches a valid DOI pointing at the wrong paper.

    python3 scripts/build_references_bib.py            # fetch, verify, write seed + report
    python3 scripts/build_references_bib.py --check     # verify only, write nothing
    python3 scripts/build_references_bib.py --strict    # refuse to write on any mismatch
"""
