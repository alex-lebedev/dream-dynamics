        "than the note and throws when it does not resolve, which silently empties its sidebar.",
        "",
        "`nature-brackets.csl` is vendored beside the manuscript (CC BY-SA 3.0) so the build does",
        "not depend on a Zotero install. Swap it for `scientific-reports.csl` or the target",
        "journal's style; nothing else changes.",
        "",
        "## If you route this through Zotero",
        "",
        "Optional — the build above does not need it. But if you want Zotero as the editing",
        "surface, one setting is load-bearing:",
        "",
        "1. Import `references-seed.bib` into Zotero (File → Import).",
        "2. **Pin the imported citation keys.** The keys in this seed are the ones the manuscript",
        "   cites. If Better BibTeX regenerates them from its own formula, every `[@key]` marker",
        "   in the manuscript breaks at once. Import with keys pinned, or reconcile afterwards.",
